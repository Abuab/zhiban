/**
 * 生成 8 维度 × 3 档位的区块
 * orderNo 由数据显式给定（保证同一维度在报告中占固定位置，只有命中档位的那一行会被渲染）。
 */
function buildDimensionBlocks(): ReportTemplateBlockSeed[] {
  const blocks: ReportTemplateBlockSeed[] = [];
  for (const dimension of DIMENSION_COPY) {
    for (const level of GAP_LEVELS) {
      const variant = dimension.levels[level];
      blocks.push({
        blockKey: dimension.code,
        orderNo: variant.orderNo,
        gapLevel: level,
        minChars: DIMENSION_MIN_CHARS,
        templateText: [
          '在「{维度名}」上，你 {分数A} 分，{昵称B} {分数B} 分，相差 {差值} 分，属于「{档位}」。',
          variant.text,
          TALK_LEAD,
          ...dimension.talk.map((line) => `· ${line}`),
        ].join('\n'),
      });
    }
  }
  return blocks;
}

